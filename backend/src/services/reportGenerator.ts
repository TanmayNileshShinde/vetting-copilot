import { DueDiligenceReport } from "./analysisEngine";

export class ReportGenerator {
  generateMarkdownDossier(report: DueDiligenceReport): string {
    return `# INSTITUTIONAL DUE DILIGENCE AUDIT REPORT
**Entity:** ${report.companyName} (${report.targetDomain})
**Audit Reference:** ${report.auditId}
**Generated Date:** ${new Date(report.timestamp).toUTCString()}
**Audit Engine:** VettingCopilot Enterprise v1.0 (Track C1 Edition)

---

## 1. EXECUTIVE VERDICT & RISK SCORING
* **Composite Risk Score:** ${report.compositeRiskScore} / 100
* **Risk Categorization:** ${report.riskLevel}
* **Official Recommendation:** ${report.recommendation}

### Pillar Breakdown
- **Leadership Stability:** ${report.pillars.leadershipScore} / 100
- **Regulatory Compliance:** ${report.pillars.regulatoryScore} / 100
- **Headcount Health:** ${report.pillars.headcountScore} / 100
- **Operational Footprint:** ${report.pillars.operationalScore} / 100

---

## 2. EXECUTIVE SUMMARY
${report.executiveSummary}

---

## 3. VERIFIED B2B FIRMOGRAPHICS (Crustdata API)
* **Estimated Headcount:** ${report.firmographics.headcountEstimate} employees
* **Annual Growth Velocity:** ${report.firmographics.headcountGrowthRate}
* **Funding & Maturity Tier:** ${report.firmographics.fundingStage}
* **Global Headquarters:** ${report.firmographics.hqLocation}
* **Data Source:** ${report.firmographics.source}

---

## 4. PUBLIC WEB & REGULATORY EVIDENCE ANCHORS (Olostep API)
${report.evidenceItems
  .map(
    (ev, idx) => `### Evidence #${idx + 1}: ${ev.title} [${ev.severity.toUpperCase()}]
- **Category:** ${ev.category}
- **Finding:** ${ev.finding}
- **Anchor Citation / Stat:** "${ev.quoteOrStat}"
- **Attribution:** ${ev.source}
`
  )
  .join("\n")}

---

## 5. MEASURED EFFICIENCY BENCHMARKS
* **Manual Analyst Hours Replaced:** ${report.benchmarkComparison.manualHoursSaved} hours
* **Direct Cost Savings:** $${report.benchmarkComparison.costSavedUsd} USD
* **Omission / Error Reduction:** ${report.benchmarkComparison.analystErrorRateReductionPct}%

---
*Confidential — Generated by VettingCopilot for Homingo Hackathon (Edition 01)*
`;
  }
}

export const reportGenerator = new ReportGenerator();
